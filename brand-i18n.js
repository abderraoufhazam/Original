window.BRAND_LANG = localStorage.getItem("brand_lang") || "ar";

window.t = function (key) {
  return (window.BRAND_I18N[window.BRAND_LANG] || window.BRAND_I18N.ar)[key] || key;
};

window.applyBrandLang = function (lang) {
  window.BRAND_LANG = lang;
  localStorage.setItem("brand_lang", lang);
  const isRTL = lang === "ar";
  document.documentElement.setAttribute("dir", isRTL ? "rtl" : "ltr");
  document.documentElement.setAttribute("lang", lang);

  // النصوص الثابتة
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = window.t(el.getAttribute("data-i18n"));
  });

  // مؤشر اللغة النشط
  document.querySelectorAll("[data-lang]").forEach(b => {
    b.classList.toggle("lang-active", b.getAttribute("data-lang") === lang);
  });

  // إعادة رسم المحتوى الديناميكي
  if (typeof window.reRenderBrand === "function") window.reRenderBrand();
};
